export const ICON_LIBRARY = Object.entries(REGISTRY).map(([name, [Component, label, group]]) => ({
  name,
  label,
  group,
  Component,
}));

const GROUPS = ['Workshop', 'Diagnostics', 'Tyres & wheels', 'Cooling & fluids', 'Electrical', 'Body & paint', 'Comfort', 'Service & care', 'Business'];

export const ICON_GROUPS = GROUPS.map((group) => ({
  group,
  icons: ICON_LIBRARY.filter((icon) => icon.group === group),
}));

export const DEFAULT_ICON = 'wrench';

export function getIcon(name) {
  return REGISTRY[name]?.[0] || Wrench;
}

export function isKnownIcon(name) {
  return Boolean(name && REGISTRY[name]);
}

export function CategoryIcon({ name, size = 20, strokeWidth = 1.6, ...rest }) {
  const Component = getIcon(name);
  return <Component size={size} strokeWidth={strokeWidth} aria-hidden="true" {...rest} />;
}
